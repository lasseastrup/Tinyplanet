import { DEFAULT_PARAMS, sanitizeParams, type PlanetParams } from './params';

export interface Preset {
  id: string;
  label: string;
  /** Planet class shown under the name. */
  kind: string;
  /** Swatch colours for the preset chip. */
  swatch: [string, string];
  params: PlanetParams;
}

function preset(id: string, label: string, kind: string, swatch: [string, string], patch: Partial<PlanetParams>): Preset {
  return { id, label, kind, swatch, params: sanitizeParams({ ...DEFAULT_PARAMS, ...patch, preset: id }) };
}

